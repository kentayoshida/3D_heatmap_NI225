const SECTOR_POOL = ['電気機器','機械','化学','化学','小売業','サービス業','建設業','食料品',
  '不動産業','銀行業','輸送用機器','情報・通信業','医薬品','卸売業','精密機器','その他製品'];
let padIdx = 1;
while (BASE.length < 225) {
  const s = SECTOR_POOL[padIdx % SECTOR_POOL.length];
  BASE.push([`X${(9000 + padIdx)}`, `${s.slice(0,2)}関連${padIdx}`, s, 0.3 + (padIdx % 5) * 0.15]);
  padIdx++;
}
const CONST = BASE.slice(0, 225);

// ---- per-period market character --------------------------------------------
// drift = index-wide bias (%), vol = spread multiplier, cap = |change| clamp.
const PERIODS = {
  '1D':  { drift: -1.4, vol: 2.6, cap: 13,  asOf: '2026-07-28T15:00:00+09:00' },
  '1W':  { drift: -0.6, vol: 3.6, cap: 20,  asOf: '2026-07-28T15:00:00+09:00' },
  '1M':  { drift:  1.8, vol: 5.5, cap: 32,  asOf: '2026-07-28T15:00:00+09:00' },
  '3M':  { drift:  4.5, vol: 8.5, cap: 48,  asOf: '2026-07-28T15:00:00+09:00' },
  '6M':  { drift:  6.0, vol: 12,  cap: 70,  asOf: '2026-07-28T15:00:00+09:00' },
  'YTD': { drift:  9.5, vol: 14,  cap: 85,  asOf: '2026-07-28T15:00:00+09:00' },
  '1Y':  { drift: 12.0, vol: 20,  cap: 130, asOf: '2026-07-28T15:00:00+09:00' },
};

function build() {
  const out = {};
  const sectors = [...new Set(CONST.map(c => c[2]))];
  let pSeed = 12345;
  for (const [pkey, cfg] of Object.entries(PERIODS)) {
    const rand = rng(pSeed++);
    const g = makeGauss(rand);
    // shared per-sector shock for this period
    const sectorShock = {};
    for (const s of sectors) sectorShock[s] = g(0, cfg.vol * 0.45);
    const constituents = CONST.map(([code, name, sector, pw]) => {
      const raw = cfg.drift + sectorShock[sector] + g(0, cfg.vol);
      const changePct = Math.max(-cfg.cap, Math.min(cfg.cap, raw));
      const contribution = pw * changePct;               // signed index points
      return {
        code,
        name,
        sector,
        changePct: Math.round(changePct * 100) / 100,
        contribution: Math.round(contribution * 100) / 100,
      };
    });
    out[pkey] = { asOf: cfg.asOf, constituents };
  }
  return out;
}

