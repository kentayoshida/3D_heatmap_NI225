// Generates data/ni225.js — realistic *sample* Nikkei 225 data for 7 periods.
// The visualization consumes window.NI225_DATA; swap this file for real data later.
//
//   node scripts/gen_sample.mjs
//
// Model: the Nikkei 225 is a price-weighted index, so a constituent's point
// contribution ≈ (its per-1% weight) × (its % change).  We assign each name a
// `pw` (index points contributed per +1% move) and, per period, a % change built
// from a market drift + sector component + idiosyncratic noise.  contribution is
// then pw × changePct.  Values are illustrative, not real quotes.

